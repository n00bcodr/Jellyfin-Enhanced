#!/usr/bin/env python3
"""Generate the typed aspect snapping table from TechnicalQualityRules.cs; client-build owns the JS."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERVER = ROOT / 'Jellyfin.Plugin.JellyfinEnhanced/Shared/MediaTags/PosterTags/Resolution/TechnicalQualityRules.cs'
WEB = ROOT / 'client/src/features/media-tags/types/quality/quality-data.ts'
START = '    // Generated by scripts/generate_technical_ratios.py; edit TechnicalQualityRules.cs.\n'
END = '    // End generated aspect ratios.\n'


def main():
    """Write or check the deterministic web table, preserving surrounding renderer code."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = SERVER.read_text().split('[] Ratios =', 1)[1].split('};', 1)[0]
    ratios = []
    for value, tolerance, label in re.findall(r'\(([\d.d /]+),\s*([\d.]+),\s*"([^"]+)"\)', source):
        parts = [float(part.strip().removesuffix('d')) for part in value.split('/')]
        ratio = parts[0] if len(parts) == 1 else parts[0] / parts[1]
        ratios.append([ratio, float(tolerance), label])
    if not ratios:
        raise SystemExit('No server aspect ratios found')
    table = START + '    const ratios: readonly (readonly [number, number, string])[] = ' + json.dumps(ratios, separators=(',', ':')) + ';\n' + END
    old = WEB.read_text()
    if old.count(START) != 1 or old.count(END) != 1:
        raise SystemExit('Missing or duplicate web aspect table markers')
    before, tail = old.split(START)
    _, after = tail.split(END)
    output = before + table + after
    if args.check:
        if old != output:
            raise SystemExit('Technical ratios are stale: run scripts/generate_technical_ratios.py')
    else:
        WEB.write_text(output)


if __name__ == '__main__':
    main()
