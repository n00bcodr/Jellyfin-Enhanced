#!/usr/bin/env python3
"""Generate the typed genre table from js/tags/genre-icons.json, which native code embeds; client-build owns the JS."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Jellyfin.Plugin.JellyfinEnhanced/js/tags/genre-icons.json'
WEB = ROOT / 'client/src/features/media-tags/types/genre/genre-table.ts'
START = '    // Generated by scripts/generate_genre_labels.py; edit genre-icons.json.\n'
END = '    // End generated genre table.\n'
# The file header (frontend.md §5.3): the generator owns it, so --check fails when it is missing.
HEADER = '// Generated by scripts/generate_genre_labels.py from js/tags/genre-icons.json, which native posters also read. Do not edit.\n'
INDENT = ' ' * 8


def unique_pairs(pairs):
    """Reject duplicate keys, which json.loads would silently drop."""
    out = {}
    for key, value in pairs:
        if key in out:
            raise SystemExit(f'genre-icons.json: duplicate key {key!r}')
        out[key] = value
    return out


def load():
    """Read and check the table: one glyph per label, every glyph a label, no name in two languages."""
    data = json.loads(SOURCE.read_text(), object_pairs_hook=unique_pairs)
    names, labels, other = data['names'], data['labels'], data['other']['key']
    flat = {}
    for language, table in names.items():
        for name, icon in table.items():
            if name in flat:
                raise SystemExit(f'genre-icons.json: {name!r} appears in two languages ({language})')
            flat[name] = icon
    english = names['English']
    icons = {}
    for key in labels:
        if key == other or key == '*' or english.get(key) is None or key != key.lower():
            raise SystemExit(f'genre-icons.json: label {key!r} must be a lowercase English genre of the table')
        if english[key] in icons:
            raise SystemExit(f'genre-icons.json: labels {icons[english[key]]!r} and {key!r} share the glyph {english[key]!r}')
        icons[english[key]] = key
    for name, icon in flat.items():
        if icon not in icons:
            raise SystemExit(f'genre-icons.json: {name!r} draws {icon!r}, which no label owns')
    if data['defaultIcon'] in icons:
        raise SystemExit('genre-icons.json: the default glyph must belong to the Other label only')
    return data, icons


def js_entries(table):
    """`'name': 'icon'` pairs wrapped like the hand-written table was."""
    lines, line = [], ''
    for name, icon in table.items():
        item = f'{json.dumps(name, ensure_ascii=False)}: {json.dumps(icon, ensure_ascii=False)},'
        if line and len(INDENT) + len(line) + 1 + len(item) > 120:
            lines.append(INDENT + line)
            line = item
        else:
            line = f'{line} {item}' if line else item
    if line:
        lines.append(INDENT + line)
    return lines


def main():
    """Write or check the deterministic web table, preserving the surrounding module."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data, icons = load()
    out = [START.rstrip('\n'), '    const genreIconMap = {', f'{INDENT}// Default', f'{INDENT}"default": {json.dumps(data["defaultIcon"])},']
    for language, table in data['names'].items():
        out.append('')
        out.append(f'{INDENT}// {language}')
        out.extend(js_entries(table))
    out[-1] = out[-1].rstrip(',')
    out.append('    };')
    out.append('')
    out.append('    // Tag Styles label of each glyph (the canonical English genre); anything else is Other.')
    out.append('    const genreLabelOfIcon = {')
    out.extend(js_entries(icons))
    out[-1] = out[-1].rstrip(',')
    out.append('    };')
    out.append(f'    const genreOtherLabel = {json.dumps(data["other"]["key"])};')
    table = '\n'.join(out) + '\n' + END
    old = WEB.read_text()
    if old.count(START) != 1 or old.count(END) != 1:
        raise SystemExit('Missing or duplicate web genre table markers')
    before, tail = old.split(START)
    _, after = tail.split(END)
    if not before.startswith(HEADER):
        before = HEADER + before
    output = before + table + after
    if args.check:
        if old != output:
            raise SystemExit('Genre table is stale: run scripts/generate_genre_labels.py')
    else:
        WEB.write_text(output)


if __name__ == '__main__':
    main()
