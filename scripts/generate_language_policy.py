#!/usr/bin/env python3
"""Writes the display-language policy JE applies on both sides, from the locale bundles it ships (js/locales):

- Jellyfin.Plugin.JellyfinEnhanced/js/language-policy.json, which the server embeds and reads (Helpers/LanguageTags.cs);
- the same data, between the language-policy markers, in js/enhanced/translations.js (the client's JE.languageCode and
  JE.supportedLanguageCode; translations load before the public configuration arrives, so the client carries it).

A display language JE stores, seeds or writes into Jellyfin's shared language key is a tag that passes the syntax rule
(`space` trimmed, not a `reserved` word, the `tag` expression, each variant once; canonical case) and resolves to a
`shipped` bundle, exactly or by its base language; anything else is Auto. Neither side asks Intl or CultureInfo.

Run it after adding or removing a locale file. --check exits 1 when either file is not what it would write
(tests/runner/tests/test_language_policy.py runs the same check in the tooling suite).
"""
import argparse
import json
from pathlib import Path
import re
import sys

REPO_ROOT = Path(__file__).resolve().parents[1]
POLICY = Path("Jellyfin.Plugin.JellyfinEnhanced/js/language-policy.json")
CLIENT = Path("Jellyfin.Plugin.JellyfinEnhanced/js/enhanced/translations.js")
LOCALES = Path("Jellyfin.Plugin.JellyfinEnhanced/js/locales")

ABOUT = ("Generated by scripts/generate_language_policy.py from js/locales; do not edit. The display-language rule of the "
         "server (Helpers/LanguageTags.cs) and the client (js/enhanced/translations.js, which carries a generated copy): "
         "trim the 'space' characters; a 'reserved' word (any case) is no tag; else the 'tag' expression with each variant "
         "once, in canonical case (language lower, Script title, REGION upper, variants lower). A tag is accepted when it "
         "or its language is a 'shipped' bundle (any case); anything else is Auto.")
SPACE = " \t\n\r\f\v"
RESERVED = ["undefined", "null", "nan", "true", "false"]
# A 2-3 letter language, then an optional 4-letter script, an optional region (2 letters or 3 digits) and variants (5-8
# letters or digits, or a digit and 3 more). No extensions or private use. ASCII classes only: the same in JS and .NET.
TAG = ("^(?<language>[A-Za-z]{2,3})(?:-(?<script>[A-Za-z]{4}))?(?:-(?<region>[A-Za-z]{2}|[0-9]{3}))?"
       "(?<variants>(?:-(?:[A-Za-z0-9]{5,8}|[0-9][A-Za-z0-9]{3}))*)$")

BEGIN = "    // BEGIN language-policy: generated from js/language-policy.json by scripts/generate_language_policy.py (do not edit)\n"
END = "    // END language-policy\n"
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


def policy(root=REPO_ROOT):
    """The policy for the locale files under root (codes sorted the way the server sorts them, case-insensitively)."""
    shipped = sorted((p.stem for p in (root / LOCALES).glob("*.json")), key=str.upper)
    return {"about": ABOUT, "space": SPACE, "reserved": RESERVED, "tag": TAG, "shipped": shipped}


def render_policy(data):
    return json.dumps(data, indent=2) + "\n"


def render_block(data):
    """The client copy: a JSON object literal (one key per line) without the note."""
    lines = [f"        {json.dumps(k)}: {json.dumps(v)}" for k, v in data.items() if k != "about"]
    return BEGIN + "    const LANGUAGE_POLICY = {\n" + ",\n".join(lines) + "\n    };\n" + END


def client_copy(source):
    """The policy data the client source carries (between the markers)."""
    match = BLOCK.search(source)
    if not match:
        raise ValueError("translations.js has no language-policy block")
    literal = match.group(0)[len(BEGIN):-len(END)].strip()
    return json.loads(literal[len("const LANGUAGE_POLICY = "):].rstrip(";"))


def outputs(root=REPO_ROOT):
    data = policy(root)
    source = (root / CLIENT).read_text(encoding="utf-8")
    if not BLOCK.search(source):
        raise ValueError(f"{CLIENT} has no language-policy block")
    return {POLICY: render_policy(data), CLIENT: BLOCK.sub(lambda _: render_block(data), source, count=1)}


def stale(root=REPO_ROOT):
    """The files (relative paths) that are not what this script would write."""
    result = []
    for relative, text in outputs(root).items():
        path = root / relative
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            result.append(str(relative))
    return result


def write(root=REPO_ROOT):
    for relative, text in outputs(root).items():
        (root / relative).write_text(text, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when a file is out of date instead of writing it")
    args = parser.parse_args()
    if args.check:
        out_of_date = stale()
        if out_of_date:
            print("Out of date (run scripts/generate_language_policy.py): " + ", ".join(out_of_date), file=sys.stderr)
            return 1
        print("Language policy is current.")
        return 0
    write()
    print(f"Wrote {POLICY} and the policy block in {CLIENT} ({len(policy()['shipped'])} shipped bundles).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
