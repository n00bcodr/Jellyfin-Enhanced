import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));
const sourceDirectory = 'Jellyfin.Plugin.JellyfinEnhanced/js/tags';
// The typed projections live with their tag type (frontend.md §1b).
const typescriptPaths = {
  status: 'client/src/features/media-tags/types/status/status-vocabulary.ts',
  quality: 'client/src/features/media-tags/types/quality/compact-quality.ts',
};
const nativePath = 'Jellyfin.Plugin.JellyfinEnhanced/Shared/MediaTags/PosterTags/Resolution/QualityCompactLabels.g.cs';
const csharpString = value => JSON.stringify(value).replace(/[\u007f-\uffff]/g, character => `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`);

/** One projection owner; client-build alone owns executable JS and its source maps. */
export function tagDataArtifacts(root, kind) {
  if (!['status', 'quality'].includes(kind)) throw new Error(`Unknown tag data projection: ${kind}`);
  const source = `${sourceDirectory}/${kind === 'status' ? 'status-vocabulary' : 'quality-compact'}.json`;
  const data = JSON.parse(readFileSync(resolve(root, source), 'utf8'));
  if (kind === 'status') return new Map([
    [typescriptPaths.status, `// Generated by scripts/generate_status_vocabulary.py; edit js/tags/status-vocabulary.json.\nexport const statusVocabulary = ${JSON.stringify(data, null, 4)} as const;\n`],
  ]);
  for (const [key, value] of Object.entries(data)) {
    if (!Array.isArray(value) || value.length !== 2 || typeof value[0] !== 'string' || typeof value[1] !== 'boolean') {
      throw new Error(`Invalid compact quality entry ${key}: expected [text, keepChannels].`);
    }
  }
  const web = `// Generated by scripts/generate_quality_compact.py; edit js/tags/quality-compact.json.\nexport const COMPACT_QUALITY: Readonly<Record<string, readonly [string, boolean]>> = ${JSON.stringify(data, null, 4)};\n`;
  let native = '// Generated by scripts/generate_quality_compact.py; edit js/tags/quality-compact.json.\nusing System.Collections.Generic;\n\nnamespace Jellyfin.Plugin.JellyfinEnhanced.Shared.MediaTags.PosterTags.Resolution;\n\ninternal static class QualityCompactLabels\n{\n    internal static readonly IReadOnlyDictionary<string, (string Text, bool KeepChannels)> Labels =\n        new Dictionary<string, (string, bool)>(System.StringComparer.Ordinal)\n        {\n';
  for (const [key, [text, keep]] of Object.entries(data)) native += `            [${csharpString(key)}] = (${csharpString(text)}, ${keep}),\n`;
  native += '        };\n}\n';
  return new Map([[typescriptPaths.quality, web], [nativePath, native]]);
}

export function synchronizeTagData({ root = repositoryRoot, kind, check = false }) {
  const artifacts = tagDataArtifacts(root, kind);
  const stale = [...artifacts].filter(([path, output]) => !existsSync(resolve(root, path)) || readFileSync(resolve(root, path), 'utf8') !== output);
  if (check && stale.length) throw new Error(`Stale ${kind} vocabulary: run scripts/generate_${kind === 'status' ? 'status_vocabulary.py --table-only' : 'quality_compact.py'}, then npm run client:build.\n${stale.map(([path]) => path).join('\n')}`);
  for (const [path, output] of check ? [] : stale) {
    mkdirSync(dirname(resolve(root, path)), { recursive: true });
    writeFileSync(resolve(root, path), output);
  }
  return { kind, changed: stale.length };
}

/** Build/check/typecheck and MSBuild reject JSON/projection drift before bundling. */
export function checkTagData(root, entries) {
  for (const [output, kind] of [['js/tags/status-vocabulary.js', 'status'], ['js/core/tag-layout.js', 'quality']]) {
    if (entries.some(entry => entry.output === output)) synchronizeTagData({ root, kind, check: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    const selected = args.filter(arg => arg === '--status' || arg === '--quality');
    if (selected.length !== 1 || args.some(arg => !['--status', '--quality', '--check'].includes(arg)) || args.length !== new Set(args).size) {
      throw new Error('Usage: node scripts/tag-data.mjs (--status | --quality) [--check]');
    }
    synchronizeTagData({ kind: selected[0].slice(2), check: args.includes('--check') });
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
