#!/usr/bin/env python3
"""Generate the shared web/native compact quality vocabulary."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Jellyfin.Plugin.JellyfinEnhanced/js/tags/quality-compact.json'
WEB = ROOT / 'Jellyfin.Plugin.JellyfinEnhanced/js/core/tag-layout.js'
NATIVE = ROOT / 'Jellyfin.Plugin.JellyfinEnhanced/Services/PosterTags/Resolution/QualityCompactLabels.g.cs'


def main():
    """Write or check both deterministic projections of the source table."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text())
    web = '    // Generated by scripts/generate_quality_compact.py; edit tags/quality-compact.json.\n    const COMPACT_QUALITY = ' + json.dumps(data, ensure_ascii=False) + ';'
    current = WEB.read_text()
    projected = re.sub(r'    /\*\* Compact quality labels;[^\n]*\*/\n    const COMPACT_QUALITY = [^\n]+;|    // Generated by scripts/generate_quality_compact.py;[^\n]*\n    const COMPACT_QUALITY = [^\n]+;', lambda _: web, current)
    native = '// Generated by scripts/generate_quality_compact.py; edit js/tags/quality-compact.json.\nusing System.Collections.Generic;\n\nnamespace Jellyfin.Plugin.JellyfinEnhanced.Services.PosterTags.Resolution;\n\ninternal static class QualityCompactLabels\n{\n    internal static readonly IReadOnlyDictionary<string, (string Text, bool KeepChannels)> Labels =\n        new Dictionary<string, (string, bool)>(System.StringComparer.Ordinal)\n        {\n'
    for key, (text, keep) in data.items():
        native += f'            [{json.dumps(key)}] = ({json.dumps(text)}, {str(keep).lower()}),\n'
    native += '        };\n}\n'
    for path, output in [(WEB, projected), (NATIVE, native)]:
        if args.check:
            if not path.exists() or path.read_text() != output:
                raise SystemExit(f'Stale compact vocabulary: {path}')
        else:
            path.write_text(output)


if __name__ == '__main__':
    main()
