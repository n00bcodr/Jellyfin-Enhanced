#!/usr/bin/env python3
"""Generate the web Status vocabulary from the JSON table embedded by the native resolver."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Jellyfin.Plugin.JellyfinEnhanced/js/tags/status-vocabulary.json"
TARGET = SOURCE.with_suffix(".js")


def main():
    """Write or check the deterministic, IIFE-wrapped web table."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    subprocess.run(["node", str(ROOT / "scripts/generate_status_dates.mjs"), *(["--check"] if args.check else [])], check=True)
    data = json.loads(SOURCE.read_text())
    output = ("// Generated by scripts/generate_status_vocabulary.py; edit status-vocabulary.json.\n"
              "(function (JE) {\n    'use strict';\n    JE.statusVocabulary = "
              + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n})(window.JellyfinEnhanced);\n")
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != output:
            raise SystemExit("Status vocabulary is stale: run scripts/generate_status_vocabulary.py")
    else:
        TARGET.write_text(output)


if __name__ == "__main__":
    main()
