    /// <summary>
    /// Builds and sends the opt-in usage report. BuildPayload is the single
    /// source of truth for what goes out: the config page's preview panel
    /// and the real send both call it, so they can't drift apart. Unlike
    /// GetPublicConfig()'s hand-picked allowlist, the config-flag section here
    /// is generated by reflecting over every bool on PluginConfiguration, so
    /// adding a feature toggle elsewhere doesn't require touching this file.
    /// Send failures only ever get a warning log; this must never be visible
    /// to a user or block anything else the plugin does.
    /// </summary>
    public class AnalyticsReportingService
    {
