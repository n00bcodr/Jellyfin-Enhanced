    public static IReadOnlyList<HostEndpoint> HostEndpoints { get; } = LoadHost();

    private static IReadOnlyList<HostEndpoint> LoadHost()
    {
        var rows = new List<HostEndpoint>();
        foreach (var host in new[] { "12.2", "10.11.11" })
        {
            using var stream = typeof(PrivacySurfaceModelTests).Assembly.GetManifestResourceStream("JE.Tests.HostEndpoints." + host)!;
            using var reader = new StreamReader(stream);
            while (reader.ReadLine() is { } line)
            {
                if (line.StartsWith('#') || line.Length == 0) continue;
                var c = line.Split('\t');
                rows.Add(new(host, c[0], c[1], c[2], c[3], c.Length > 4 ? c[4] : ""));
            }
        }
        return rows;
    }

