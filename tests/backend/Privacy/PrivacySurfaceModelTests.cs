    /// <summary>The oracle's Hidden Content surface (null: never hidden) and whether Spoiler Guard strips the answer.</summary>
    public static (string? Hc, bool Sg) Expected(string endpoint)
        => Lists.Contains(endpoint) ? ("library", true) : Scoped.TryGetValue(endpoint, out var scope) ? ((string?)scope, true)
            : Untouched.Contains(endpoint) || NestedOnly.Contains(endpoint) ? ((string?)null, false) : ((string?)null, true);

    /// <summary>The endpoints the model covers: every title-carrying host endpoint plus Home Screen Sections.</summary>
    public static IEnumerable<string> NativeSurfaces() => TitleEndpoints.Keys.Append("HomeScreen.GetSectionContent").Distinct().OrderBy(k => k, StringComparer.Ordinal);

    public static readonly string[] JeSurfaces = ["je:activity", "je:provider-json", "je:elsewhere"];
    public static readonly string[] Kinds = ["tmdb", "jellyfin-id", "collection-member", "episode"];
    public static readonly string[] Rules = ["hc-global", "hc-surface", "sg-item", "sg-collection"];
    public static readonly string[] Moments = ["before", "in-flight"];

    private static string? HcSurfaceOf(string surface) => surface switch
    {
        "je:activity" => "library",
        "je:provider-json" or "je:elsewhere" => "discovery",
        _ => Expected(surface).Hc
    };

    public static IEnumerable<object[]> Cells()
    {
        foreach (var surface in NativeSurfaces().Concat(JeSurfaces).Except(HostShapedOnly))
        foreach (var kind in Kinds)
        foreach (var rule in Rules)
        foreach (var moment in Moments)
        {
            // A collection guards its members (Spoiler Guard); Hidden Content has no collection rule.
            if ((rule == "sg-collection") != (kind == "collection-member")) continue;
            // A surface-scoped hide needs a scoped surface (library lists only take global hides).
            if (rule == "hc-surface" && HcSurfaceOf(surface) is null or "library") continue;
            // Provider JSON and Elsewhere address titles by TMDB id: a title without one never appears there.
            if (surface is "je:provider-json" or "je:elsewhere" && kind is "jellyfin-id" or "episode") continue;
            yield return new object[] { surface, kind, rule, moment };
        }
    }

