        /// <summary>Saves the cell's rule.</summary>
        public void Commit(string rule, string kind, string? scope)
        {
            var id = User.ToString("N");
            if (rule.StartsWith("hc-", StringComparison.Ordinal))
            {
                var entry = kind switch
                {
                    "tmdb" => new HiddenContentItem { Type = "Movie", TmdbId = "603" },
                    "jellyfin-id" => new HiddenContentItem { ItemId = MovieId.ToString("D"), Type = "Movie" },
                    _ => new HiddenContentItem { ItemId = Series.ToString("D"), Type = "Series" }
                };
                entry.HideScope = rule == "hc-surface" ? scope! : "global";
                F.Core.Manager.SaveUserConfiguration(id, "hidden-content.json", new UserHiddenContent
                {
                    Settings = new() { FilterSearch = true },
                    Items = new() { [kind == "tmdb" ? "movie:tmdb:603" : "rule"] = entry }
                });
                HiddenContentResponseFilter.InvalidateUser(id);
                return;
            }
            var state = new UserSpoilerBlur();
            switch (kind)
            {
                case "tmdb": state.ProviderTitles["movie:tmdb:603"] = new(); break;
                case "jellyfin-id": state.Movies[MovieId.ToString("N")] = new(); break;
                case "collection-member": state.Collections[Collection.ToString("N")] = new(); break;
                default: state.Series[Series.ToString("N")] = new(); break;
            }
            F.Core.Manager.SaveUserConfiguration(id, "spoilerblur.json", state);
            SpoilerUserResolver.InvalidateUser(id);
        }

