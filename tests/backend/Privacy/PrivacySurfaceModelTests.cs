    private static ActionContext NativeContext(Rig rig, string controller, string action, Guid itemId)
    {
        var http = new DefaultHttpContext { User = TestCallers.Principal(rig.User, false) };
        http.Request.Method = action == "GetPostedPlaybackInfo" || action.StartsWith("Authenticate", StringComparison.Ordinal) || action == "OpenLiveStream" ? "POST" : "GET";
        http.Request.Path = $"/{controller}/{itemId:N}/{action}";
        var values = new RouteValueDictionary { ["controller"] = controller, ["action"] = action, ["itemId"] = itemId.ToString("N") };
        http.Request.RouteValues = values;
        var descriptor = new ControllerActionDescriptor
        {
            ControllerName = controller, ActionName = action, DisplayName = controller + "." + action,
            RouteValues = new Dictionary<string, string?> { ["controller"] = controller, ["action"] = action }
        };
        return new ActionContext(http, new RouteData(values), descriptor, new ModelStateDictionary());
    }

    /// <summary>Runs Hidden Content's and Spoiler Guard's action filters around the action, then the final gate.</summary>
    private static async Task<(IActionResult Result, string Body)> DeliverNative(Rig rig, string endpoint, string kind, string rule, string moment)
    {
        var (controller, action) = (endpoint.Split('.')[0], endpoint.Split('.')[1]);
        var context = NativeContext(rig, controller, action, rig.Target(kind));
        var scope = Expected(endpoint).Hc;
        if (moment == "before") rig.Commit(rule, kind, scope);
        var result = new ObjectResult(rig.Value(TitleEndpoints.GetValueOrDefault(endpoint) ?? "QueryResult<BaseItemDto>", kind));
        var filters = new List<IFilterMetadata>();
        Task<ActionExecutedContext> Action()
        {
            if (moment == "in-flight") rig.Commit(rule, kind, scope);
            return Task.FromResult(new ActionExecutedContext(context, filters, new object()) { Result = result });
        }
        var strip = new ActionExecutingContext(context, filters, new Dictionary<string, object?>(), new object());
        ActionExecutionDelegate inner = async () => { ActionExecutedContext? done = null; await rig.Strip.OnActionExecutionAsync(strip, async () => done = await Action()); return done!; };
        await new HiddenContentResponseFilter(rig.F.Core.Manager, rig.F.Core.Logger, rig.Library.Object)
            .OnActionExecutionAsync(new ActionExecutingContext(context, filters, new Dictionary<string, object?>(), new object()), inner);
        var delivery = new ResultExecutingContext(context, filters, result, new object());
        new TitlePresentationResultFilter(rig.F.Core.Manager, rig.Spoilers, rig.Library.Object, Mock.Of<MediaBrowser.Controller.IServerApplicationHost>(), rig.Strip)
            .OnResultExecuting(delivery);
        var value = (delivery.Result as ObjectResult)?.Value;
        return (delivery.Result, value == null ? "" : JsonSerializer.Serialize(value, value.GetType()));
    }

    /// <summary>A JE endpoint resolved by real routing: the request caches hold the policy the action read, then delivery.</summary>
    private static string DeliverJe(Rig rig, string surface, string kind, string rule, string moment)
    {
        var tmdb = rig.Tmdb(kind);
        var (path, raw) = surface switch
        {
            "je:activity" => ("/JellyfinEnhanced/activity", """{"items":[{"activityType":"Reviewed","userId":"u","userName":"Viewer","timestamp":1,"content":"Secret review","rating":9,"item":{"id":"TARGET","name":"NAME","type":"TYPE","hasPrimaryImage":true}},{"activityType":"Reviewed","userId":"u","userName":"Viewer","timestamp":2,"content":"kept review","item":{"id":"KEPT","name":"Kept","type":"Movie","hasPrimaryImage":true}}]}"""),
            "je:provider-json" => ($"/JellyfinEnhanced/tmdb/movie/{tmdb}", """{"id":TMDB,"title":"Movie","overview":"Secret plot","vote_average":8.1}"""),
            _ => ($"/JellyfinEnhanced/tmdb/movie/{tmdb}/watch/providers", """{"id":TMDB,"secretNote":"Secret","results":{"US":{"link":"https://tmdb.test/watch","flatrate":[{"provider_id":8,"provider_name":"Netflix","logo_path":"/n.png","display_priority":1}]}}}""")
        };
        raw = raw.Replace("TARGET", rig.Target(kind).ToString("N")).Replace("KEPT", rig.Kept.ToString("N")).Replace("TMDB", tmdb.ToString())
            .Replace("NAME", kind == "episode" ? "Secret ending" : "Movie").Replace("TYPE", kind == "episode" ? "Episode" : "Movie");
        var context = EndpointRouting.Resolve(path, rig.User);
        Assert.IsType<ControllerActionDescriptor>(context.ActionDescriptor);
        if (moment == "before") rig.Commit(rule, kind, HcSurfaceOf(surface));
        // The action reads the policy into its request caches; an in-flight rule lands after that, before delivery.
        HiddenContentPolicy.Load(rig.F.Core.Manager, rig.User, context.HttpContext, rig.Library.Object); rig.Spoilers.Load(rig.User, context.HttpContext);
        var result = new ObjectResult(JsonNode.Parse(raw)) { StatusCode = 200 };
        if (moment == "in-flight") rig.Commit(rule, kind, HcSurfaceOf(surface));
        var delivery = new ResultExecutingContext(context, new List<IFilterMetadata>(), result, new object());
        new TitlePresentationResultFilter(rig.F.Core.Manager, rig.Spoilers, rig.Library.Object, Mock.Of<MediaBrowser.Controller.IServerApplicationHost>(), rig.Strip)
            .OnResultExecuting(delivery);
        return Assert.IsType<ContentResult>(delivery.Result).Content!;
    }

    [Theory]
    [MemberData(nameof(Cells))]
    public async Task EverySurfaceAppliesEveryRuleToEveryIdentity(string surface, string kind, string rule, string moment)
    {
        using var rig = new Rig();
        var target = rig.Target(kind);
        var hc = rule.StartsWith("hc-", StringComparison.Ordinal);
        if (surface.StartsWith("je:", StringComparison.Ordinal))
        {
            var body = DeliverJe(rig, surface, kind, rule, moment);
            if (hc)
            {
                // Activity rows are a list; a provider resource is the title's own page (never hidden).
                if (surface == "je:activity")
                {
                    Assert.DoesNotContain(target.ToString("N"), body, StringComparison.OrdinalIgnoreCase);
                    Assert.Contains("kept review", body);
                }
                else Assert.Contains("Secret", body);
            }
            else
            {
                Assert.DoesNotContain("Secret", body);
                if (surface == "je:provider-json") Assert.DoesNotContain("vote_average", body);
            }
            return;
        }
        var (result, delivered) = await DeliverNative(rig, surface, kind, rule, moment);
        var expected = Expected(surface);
        Assert.IsAssignableFrom<ObjectResult>(result);
        var declared = TitleEndpoints.GetValueOrDefault(surface) ?? "QueryResult<BaseItemDto>";
        if (NestedOnly.Contains(surface))
        {
            // A session stays; the title it plays is projected (hidden: a title-less stub; guarded: stripped).
            Assert.DoesNotContain("Secret", delivered);
            return;
        }
        var list = declared is not ("BaseItemDto" or "IEnumerable<ImageInfo>" or "PlaybackInfoResponse" or "TimerInfoDto" or "LiveStreamResponse" or "AllThemeMediaResult"
            or "AuthenticationResult" or "IReadOnlyList<SessionInfoDto>" or "QueryResult<TimerInfoDto>");
        if (hc)
        {
            // The opened item's own answers (its page, images, playback) are never hidden from it.
            if (!list) { Assert.Contains("Secret", delivered); return; }
            Assert.Equal(expected.Hc == null, delivered.Contains(target.ToString(), StringComparison.OrdinalIgnoreCase));
            Assert.Contains(rig.Kept.ToString(), delivered, StringComparison.OrdinalIgnoreCase);
        }
        else Assert.Equal(!expected.Sg, delivered.Contains("Secret", StringComparison.Ordinal));
    }

    [Fact]
    public void TheModelCoversEveryHostEndpointIdentityKindRuleAndMoment()
    {
        var cells = Cells().Select(c => ((string)c[0], (string)c[1], (string)c[2], (string)c[3])).ToArray();
        Assert.Equal(cells.Length, cells.Distinct().Count());
        // Both hosts' title-carrying endpoints are present (12.2 and 10.11.11 differ by three).
        foreach (var host in new[] { "12.2", "10.11.11" })
            foreach (var endpoint in HostEndpoints.Where(e => e.Host == host && e.TitlePath.Length > 0))
                Assert.True(cells.Any(c => c.Item1 == endpoint.Controller + "." + endpoint.Action) || HostShapedOnly.Contains(endpoint.Controller + "." + endpoint.Action),
                    endpoint.Controller + "." + endpoint.Action);
        foreach (var kind in Kinds) Assert.Contains(cells, c => c.Item2 == kind);
        foreach (var rule in Rules) foreach (var moment in Moments) Assert.Contains(cells, c => c.Item3 == rule && c.Item4 == moment);
        foreach (var surface in JeSurfaces) Assert.Contains(cells, c => c.Item1 == surface);
        Assert.True(HostEndpoints.Count(e => e.Host == "12.2" && e.TitlePath.Length > 0) >= 80);
    }
