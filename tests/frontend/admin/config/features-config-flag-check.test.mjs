import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { spawnSync } from 'node:child_process';

// Override only OUTPUT, leaving all real generator inputs in place.
test('config flag --check compares bytes and fails on drift without writing', t => {
  mkdirSync(resolve('artifacts'), { recursive: true });
  const folder = mkdtempSync(resolve('artifacts/config-check-'));
  t.after(() => rmSync(folder, { recursive: true, force: true }));
  const output = join(folder, 'groups.json');
  const generated = readFileSync('docs/advanced/config-flag-groups.json');
  const run = () => spawnSync('python3', ['-c',
    'import runpy,sys; from pathlib import Path; scope=runpy.run_path("scripts/generate_config_flag_groups.py"); scope["main"].__globals__["OUTPUT"]=Path(sys.argv[1]); sys.argv=["generate_config_flag_groups.py","--check"]; scope["main"]()', output], { encoding: 'utf8' });
  writeFileSync(output, generated);
  const before = readFileSync(output);
  assert.equal(run().status, 0, 'clean generated bytes pass');
  assert.deepEqual(readFileSync(output), before, 'a clean check preserves the bytes');
  writeFileSync(output, 'drift\n');
  assert.notEqual(run().status, 0, 'drift must fail');
  assert.equal(readFileSync(output, 'utf8'), 'drift\n', 'drift is left available to inspect');
  rmSync(output);
  assert.notEqual(run().status, 0, 'a missing output must fail');
  assert.throws(() => readFileSync(output), { code: 'ENOENT' }, 'check never creates missing output');
});
