using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using Jellyfin.Plugin.JellyfinEnhanced.Transport;

// Reflection only: no controller, plugin, configuration instance or provider is constructed.
var root = args.FirstOrDefault(a => !a.StartsWith("--", StringComparison.Ordinal))
    ?? throw new ArgumentException("Usage: ClientContracts <repository-root> [--check]");
var check = args.Contains("--check", StringComparer.Ordinal);
var generator = new ContractGenerator();
generator.Visit(typeof(BootstrapResponse));
generator.Visit(typeof(RevisionedSettingsResponse));
generator.Visit(typeof(RevisionedSettingsRequest));
generator.Visit(typeof(SettingsSaveReceipt));
generator.Visit(typeof(BookmarkMutationRequest));
generator.Visit(typeof(BookmarkSaveReceipt));
var schema = new JsonObject
{
    ["$schema"] = "https://json-schema.org/draft/2020-12/schema",
    ["$ref"] = "#/$defs/BootstrapResponse",
    ["$defs"] = generator.Definitions
};
var schemaText = schema.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n";
var types = "// Generated by tools/ClientContracts. Do not edit.\n" +
    "export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n\n" +
    string.Join("\n", generator.Interfaces.OrderBy(pair => pair.Key, StringComparer.Ordinal).Select(pair => pair.Value));
var runtimeSchema = "// Generated by tools/ClientContracts. Do not edit.\nexport const bootstrapSchema = " + schemaText.TrimEnd() + " as const;\n";
var stale = false;
foreach (var (relative, content) in new[] {
    ("contracts/bootstrap.schema.json", schemaText),
    ("client/src/contracts/generated.ts", types),
    ("client/src/contracts/schema.ts", runtimeSchema) })
{
    var path = Path.Combine(root, relative);
    if (check)
    {
        if (!File.Exists(path) || File.ReadAllText(path) != content)
        {
            Console.Error.WriteLine($"Stale contract: {relative}");
            stale = true;
        }
    }
    else
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content, new UTF8Encoding(false));
        Console.WriteLine(relative);
    }
}
return stale ? 1 : 0;

sealed class ContractGenerator
{
    private readonly NullabilityInfoContext _nullability = new();
    private readonly HashSet<Type> _visited = new();
    private readonly Dictionary<string, Type> _names = new(StringComparer.Ordinal);
    public JsonObject Definitions { get; } = new();
    public Dictionary<string, string> Interfaces { get; } = new(StringComparer.Ordinal);

    public void Visit(Type type)
    {
        if (!_visited.Add(type)) return;
        if (_names.TryGetValue(type.Name, out var existing) && existing != type)
            throw new NotSupportedException($"Duplicate wire type name: {type.Name}");
        _names[type.Name] = type;
        var properties = new JsonObject();
        var required = new JsonArray();
        var lines = new List<string>();
        foreach (var property in type.GetProperties(BindingFlags.Instance | BindingFlags.Public).OrderBy(p => p.Name, StringComparer.Ordinal))
        {
            var ignore = property.GetCustomAttribute<JsonIgnoreAttribute>();
            if (ignore?.Condition == JsonIgnoreCondition.Always) continue;
            if (property.GetIndexParameters().Length != 0 || property.GetMethod == null) continue;
            if (property.GetCustomAttribute<JsonExtensionDataAttribute>() != null)
                throw new NotSupportedException($"Extension data needs an explicit policy: {type.Name}.{property.Name}");
            var name = property.GetCustomAttribute<JsonPropertyNameAttribute>()?.Name ?? property.Name;
            var (ts, schema) = Describe(property.PropertyType, _nullability.Create(property), property.IsDefined(typeof(OpaqueBootstrapJsonAttribute)));
            var optional = ignore?.Condition is JsonIgnoreCondition.WhenWritingNull or JsonIgnoreCondition.WhenWritingDefault;
            properties[name] = schema;
            if (!optional) required.Add(name);
            lines.Add($"  {JsonSerializer.Serialize(name)}{(optional ? "?" : "")}: {ts};");
        }
        Definitions[type.Name] = new JsonObject { ["type"] = "object", ["properties"] = properties, ["required"] = required, ["additionalProperties"] = false };
        Interfaces[type.Name] = $"export interface {type.Name} {{\n{string.Join("\n", lines)}\n}}\n";
    }

    private (string Ts, JsonNode Schema) Describe(Type type, NullabilityInfo? nullable, bool opaque = false)
    {
        var underlying = Nullable.GetUnderlyingType(type);
        var allowsNull = underlying != null || (!type.IsValueType && nullable?.ReadState == NullabilityState.Nullable);
        if (underlying != null) type = underlying;
        var (ts, schema) = Core(type, nullable, opaque);
        return allowsNull && ts != "JsonValue"
            ? (ts + " | null", new JsonObject { ["anyOf"] = new JsonArray(schema, new JsonObject { ["type"] = "null" }) })
            : (ts, schema);
    }

    private (string Ts, JsonNode Schema) Core(Type type, NullabilityInfo? nullable, bool opaque)
    {
        if (type == typeof(object) || type == typeof(JsonElement) || typeof(JsonNode).IsAssignableFrom(type))
        {
            if (!opaque) throw new NotSupportedException($"Opaque transport type {type} requires [OpaqueBootstrapJson]");
            return ("JsonValue", JsonValue.Create(true)!);
        }
        if (type == typeof(string) || type == typeof(Guid) || type == typeof(DateTime) || type == typeof(DateTimeOffset))
            return ("string", new JsonObject { ["type"] = "string" });
        if (type == typeof(bool)) return ("boolean", new JsonObject { ["type"] = "boolean" });
        if (type.IsEnum) throw new NotSupportedException($"Specify the wire enum policy for {type}");
        if (type.IsPrimitive || type == typeof(decimal))
            return ("number", new JsonObject { ["type"] = type == typeof(double) || type == typeof(float) || type == typeof(decimal) ? "number" : "integer" });
        if (type.IsArray)
        {
            var (ts, schema) = Describe(type.GetElementType()!, nullable?.ElementType, opaque);
            return ($"Array<{ts}>", new JsonObject { ["type"] = "array", ["items"] = schema });
        }
        if (type.IsGenericType)
        {
            var definition = type.GetGenericTypeDefinition();
            var arguments = type.GetGenericArguments();
            if (definition == typeof(Dictionary<,>) || definition == typeof(IReadOnlyDictionary<,>))
            {
                if (arguments[0] != typeof(string)) throw new NotSupportedException("Only string-keyed JSON dictionaries are supported");
                var (ts, schema) = Describe(arguments[1], nullable?.GenericTypeArguments[1], opaque);
                return ($"Record<string, {ts}>", new JsonObject { ["type"] = "object", ["additionalProperties"] = schema });
            }
            if (definition == typeof(List<>) || definition == typeof(IReadOnlyList<>) || definition == typeof(IEnumerable<>))
            {
                var (ts, schema) = Describe(arguments[0], nullable?.GenericTypeArguments[0], opaque);
                return ($"Array<{ts}>", new JsonObject { ["type"] = "array", ["items"] = schema });
            }
            throw new NotSupportedException($"Unsupported generic transport type {type}");
        }
        if (type.Namespace?.StartsWith("Jellyfin.Plugin.JellyfinEnhanced", StringComparison.Ordinal) != true)
            throw new NotSupportedException($"Unsupported transport type {type}");
        Visit(type);
        return (type.Name, new JsonObject { ["$ref"] = "#/$defs/" + type.Name });
    }
}
